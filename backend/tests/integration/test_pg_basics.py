"""Integrationstests der Datenbankschicht gegen PostgreSQL.

Prüfen, was SQLite im Speicher nicht zeigen kann: die Migrationen selbst,
den Abgleich Modell/Migration und den Zeitstempel mit Zeitzone.
Werte der Rakete frei gewählt (Beispielrakete ohne Geometrie), NICHT
gemessen; es wird kein Flug simuliert.
"""

from dataclasses import asdict
from datetime import datetime

from alembic import command
from alembic.runtime.migration import MigrationContext
from alembic.script import ScriptDirectory
from sqlalchemy import inspect, text

from app.models import GEOMETRY_FIELDS
from app.physics.simulation import EXAMPLE_ROCKET
from pg_setup import alembic_config

ROCKET = {
    "name": "Integrationstest",
    **{k: v for k, v in asdict(EXAMPLE_ROCKET).items() if k not in GEOMETRY_FIELDS},
}


def test_database_is_at_head(pg_engine):
    head = ScriptDirectory.from_config(alembic_config()).get_current_head()
    with pg_engine.connect() as connection:
        current = MigrationContext.configure(connection).get_current_revision()
    assert current == head


def test_tables_created_by_migrations(pg_engine):
    names = set(inspect(pg_engine).get_table_names())
    assert names == {"alembic_version", "rockets", "series", "flights"}


def test_models_match_migrations(pg_engine):
    # Wirft AutogenerateDiffsDetected, wenn Modell und Migrationen abweichen.
    command.check(alembic_config())


def test_created_at_has_time_zone(pg_client):
    response = pg_client.post("/api/rockets", json=ROCKET)
    assert response.status_code == 201
    created = response.json()["created_at"]
    parsed = datetime.fromisoformat(created.replace("Z", "+00:00"))
    assert parsed.tzinfo is not None
    assert pg_client.get(f"/api/rockets/{response.json()['id']}").json() == response.json()


def test_each_test_starts_empty_with_ids_from_one(pg_client, pg_clean):
    with pg_clean.connect() as connection:
        assert connection.execute(text("SELECT count(*) FROM rockets")).scalar() == 0
    response = pg_client.post("/api/rockets", json=ROCKET)
    assert response.json()["id"] == 1